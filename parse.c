#include "minishell.h"

int	ft_is_spc(int cmd)
{

    if (33 <= cmd && cmd <= 40 || 42 <= cmd && cmd <= 126)
        return (1);
	return (-1);
}

int ft_is_spc2(int cmd)
{
    if (33 <= cmd && cmd <= 37 || 39 <= cmd && cmd <= 123 || 125 <= cmd && cmd <= 126)
        return 1;
    return -1;
}
